/* zpaqII - LZ4 block decoder written in ZPAQL (phase 2.4b).
 *
 * This is the program a zpaq block carries when it stores an LZ4 block as its
 * payload: plain zpaq 7.15 runs it and gets the original bytes back, so an
 * archive we write needs nothing of ours to be extracted.
 *
 * It is fed the compressed block one byte per call and writes the plaintext
 * with `out`, keeping the 64 KB history in M (pm = 16).  EOB (-1) halts it.
 *
 * Registers: r0 state, r1/r5/r8/r9 32-bit counter (bytes 0..3), r2 token low
 * nibble, r3 offset low byte, r6 input byte, r7 copy-done flag, r20 sum.
 * States: 0 token, 1 literal length extension, 2 literal bytes,
 * 3 offset low, 4 offset high, 5 match length extension, 6 copy the match.
 *
 * The counter is 32 bits because only the *offset* of an LZ4 match is limited
 * to 64 KB: a match (or a literal run) can be as long as the block.  A ZPAQL
 * register holds 8 bits, so the counter lives in four registers and every
 * add and subtract carries explicitly; a plain `a--` at zero would wrap to
 * 0xFFFFFFFF and the loops would never end.
 *
 * The long forms (ifl/ifnotl/elsel) are used throughout: the short jumps
 * reach only 127 bytes and the state machine is larger than that.
 */
#include "zq_internal.h"

static const char zq_lz4_program[] =
    "pcomp lz4 0 ;\n"
    "  r=a 6\n"
    "  a++\n"
    "  a== 0 ifl\n"
    "    halt\n"
    "  endif\n"
    "  a=r 0\n"
    "  a== 0 ifl\n"
    /* state 0: read the token */
    "    a=r 6\n"
    "    a>>= 4\n"
    "    r=a 1\n"
    "    a=0\n"
    "    r=a 5\n"
    "    r=a 8\n"
    "    r=a 9\n"
    "    a=r 6\n"
    "    a&= 15\n"
    "    r=a 2\n"
    "    a=r 1\n"
    "    a== 15 ifl\n"
    "      a= 1\n"
    "      r=a 0\n"
    "    elsel\n"
    "      a== 0 ifl\n"
    "        a= 3\n"
    "        r=a 0\n"
    "      elsel\n"
    "        a= 2\n"
    "        r=a 0\n"
    "      endif\n"
    "    endif\n"
    "  elsel\n"
    "    a== 1 ifl\n"
    /* state 1: literal length extension bytes: counter += byte */
    "      a=r 6\n"
    "      d=a\n"
    "      a=r 1\n"
    "      a+=d\n"
    "      r=a 20\n"
    "      a> 255 ifl\n"
    "        a=r 5\n"
    "        a++\n"
    "        a&= 255\n"
    "        r=a 5\n"
    "        a== 0 ifl\n"
    "          a=r 8\n"
    "          a++\n"
    "          a&= 255\n"
    "          r=a 8\n"
    "          a== 0 ifl\n"
    "            a=r 9\n"
    "            a++\n"
    "            a&= 255\n"
    "            r=a 9\n"
    "          endif\n"
    "        endif\n"
    "      endif\n"
    "      a=r 20\n"
    "      a&= 255\n"
    "      r=a 1\n"
    "      a=d\n"
    "      a== 255 ifl\n"
    "        a= 1\n"
    "        r=a 0\n"
    "      elsel\n"
    "        a= 2\n"
    "        r=a 0\n"
    "      endif\n"
    "    elsel\n"
    "      a== 2 ifl\n"
    /* state 2: literal bytes */
    "        a=r 6\n"
    "        *b=a\n"
    "        b++\n"
    "        out\n"
    "        a=r 1\n"
    "        a== 0 ifl\n"
    "          a= 255\n"
    "          r=a 1\n"
    "          a=r 5\n"
    "          a== 0 ifl\n"
    "            a= 255\n"
    "            r=a 5\n"
    "            a=r 8\n"
    "            a== 0 ifl\n"
    "              a= 255\n"
    "              r=a 8\n"
    "              a=r 9\n"
    "              a--\n"
    "              r=a 9\n"
    "            elsel\n"
    "              a--\n"
    "              r=a 8\n"
    "            endif\n"
    "          elsel\n"
    "            a--\n"
    "            r=a 5\n"
    "          endif\n"
    "        elsel\n"
    "          a--\n"
    "          r=a 1\n"
    "        endif\n"
    "        a=r 1\n"
    "        a== 0 ifl\n"
    "          a=r 5\n"
    "          a== 0 ifl\n"
    "            a=r 8\n"
    "            a== 0 ifl\n"
    "              a=r 9\n"
    "              a== 0 ifl\n"
    "                a= 3\n"
    "                r=a 0\n"
    "              endif\n"
    "            endif\n"
    "          endif\n"
    "        endif\n"
    "      elsel\n"
    "        a== 3 ifl\n"
    /* state 3: offset low byte */
    "          a=r 6\n"
    "          r=a 3\n"
    "          a= 4\n"
    "          r=a 0\n"
    "        elsel\n"
    "          a== 4 ifl\n"
    /* state 4: offset high byte, then set up the match */
    "            a=r 6\n"
    "            a<<= 8\n"
    "            d=a\n"
    "            a=r 3\n"
    "            a+=d\n"
    "            d=a\n"
    "            a=b\n"
    "            a-=d\n"
    "            c=a\n"
    "            a=r 2\n"
    "            a+= 4\n"
    "            a&= 255\n"
    "            r=a 1\n"
    "            a=0\n"
    "            r=a 5\n"
    "            r=a 8\n"
    "            r=a 9\n"
    "            a=r 2\n"
    "            a== 15 ifl\n"
    "              a= 5\n"
    "              r=a 0\n"
    "            elsel\n"
    "              a= 6\n"
    "              r=a 0\n"
    "            endif\n"
    "          elsel\n"
    "            a== 5 ifl\n"
    /* state 5: match length extension bytes: counter += byte */
    "              a=r 6\n"
    "              d=a\n"
    "              a=r 1\n"
    "              a+=d\n"
    "              r=a 20\n"
    "              a> 255 ifl\n"
    "                a=r 5\n"
    "                a++\n"
    "                a&= 255\n"
    "                r=a 5\n"
    "                a== 0 ifl\n"
    "                  a=r 8\n"
    "                  a++\n"
    "                  a&= 255\n"
    "                  r=a 8\n"
    "                  a== 0 ifl\n"
    "                    a=r 9\n"
    "                    a++\n"
    "                    a&= 255\n"
    "                    r=a 9\n"
    "                  endif\n"
    "                endif\n"
    "              endif\n"
    "              a=r 20\n"
    "              a&= 255\n"
    "              r=a 1\n"
    "              a=d\n"
    "              a== 255 ifl\n"
    "                a= 5\n"
    "                r=a 0\n"
    "              elsel\n"
    "                a= 6\n"
    "                r=a 0\n"
    "              endif\n"
    "            endif\n"
    "          endif\n"
    "        endif\n"
    "      endif\n"
    "    endif\n"
    "  endif\n"
    "  a=r 0\n"
    "  a== 6 ifl\n"
    /* state 6: copy the match, one byte at a time (the copy may overlap) */
    "    a=0\n"
    "    r=a 7\n"
    "    do\n"
    "      a=*c\n"
    "      *b=a\n"
    "      b++\n"
    "      out\n"
    "      c++\n"
    "      a=r 1\n"
    "      a== 0 ifl\n"
    "        a= 255\n"
    "        r=a 1\n"
    "        a=r 5\n"
    "        a== 0 ifl\n"
    "          a= 255\n"
    "          r=a 5\n"
    "          a=r 8\n"
    "          a== 0 ifl\n"
    "            a= 255\n"
    "            r=a 8\n"
    "            a=r 9\n"
    "            a--\n"
    "            r=a 9\n"
    "          elsel\n"
    "            a--\n"
    "            r=a 8\n"
    "          endif\n"
    "        elsel\n"
    "          a--\n"
    "          r=a 5\n"
    "        endif\n"
    "      elsel\n"
    "        a--\n"
    "        r=a 1\n"
    "      endif\n"
    "      a=r 1\n"
    "      a== 0 ifl\n"
    "        a=r 5\n"
    "        a== 0 ifl\n"
    "          a=r 8\n"
    "          a== 0 ifl\n"
    "            a=r 9\n"
    "            a== 0 ifl\n"
    "              a= 1\n"
    "              r=a 7\n"
    "            endif\n"
    "          endif\n"
    "        endif\n"
    "      endif\n"
    "      a=r 7\n"
    "      a== 1\n"
    "    until\n"
    "    a= 0\n"
    "    r=a 0\n"
    "  endif\n"
    "  halt\n"
    "end\n";

const char *zq_lz4_pcomp_program(void) { return zq_lz4_program; }
