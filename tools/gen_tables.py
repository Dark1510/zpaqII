#!/usr/bin/env python3
"""Generates src/core/tables.c from the reference libzpaq.cpp.

The predictor tables (sns, sdt2k, sdt, ssquasht, stdt) are algorithm data:
they are extracted from upstream instead of being transcribed by hand, and
each one's element count is verified.  Usage:

    python3 tools/gen_tables.py [path/libzpaq.cpp] > src/core/tables.c
"""
import re
import sys

path = sys.argv[1] if len(sys.argv) > 1 else \
    "/mnt/IA_LAB/agentes/zpaqII/upstream-zpaq/libzpaq.cpp"
src = open(path, encoding="utf-8", errors="surrogateescape").read()

TABLES = [
    ("sns", "zq_sns", "zq_u8", 1024,
     r"static\s+const\s+U8\s+sns\[1024\]\s*=\s*\{(.*?)\};"),
    ("sdt2k", "zq_sdt2k", "int", 256,
     r"static\s+const\s+int\s+sdt2k\[256\]\s*=\s*\{(.*?)\};"),
    ("sdt", "zq_sdt", "int", 1024,
     r"static\s+const\s+int\s+sdt\[1024\]\s*=\s*\{(.*?)\};"),
    ("ssquasht", "zq_ssquasht", "zq_u16", 1344,
     r"static\s+const\s+U16\s+ssquasht\[1344\]\s*=\s*\{(.*?)\};"),
    ("stdt", "zq_stdt", "zq_u8", 712,
     r"static\s+const\s+U8\s+stdt\[712\]\s*=\s*\{(.*?)\};"),
]


def parse(body):
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    body = re.sub(r"//[^\n]*", "", body)
    toks = [t.strip() for t in body.split(",") if t.strip()]
    vals = []
    for t in toks:
        if not re.fullmatch(r"-?(0x[0-9a-fA-F]+|\d+)", t):
            raise SystemExit("unexpected token in table: %r" % t)
        vals.append(int(t, 0))
    return vals


out = ["/* zpaqII - predictor tables. GENERATED by tools/gen_tables.py",
       " * from libzpaq.cpp (Unlicense, Matt Mahoney). Do not edit by hand. */",
       '#include "zq_internal.h"', ""]

for name, cname, ctype, expect, pat in TABLES:
    m = re.search(pat, src, re.S)
    if not m:
        raise SystemExit("table %s not found" % name)
    vals = parse(m.group(1))
    if len(vals) != expect:
        raise SystemExit("%s: %d values, expected %d" % (name, len(vals), expect))
    if ctype == "zq_u8":
        assert all(0 <= v <= 255 for v in vals), name
    if ctype == "zq_u16":
        assert all(0 <= v <= 65535 for v in vals), name
    out.append("const %s %s[%d] = {" % (ctype, cname, expect))
    for i in range(0, len(vals), 8):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + 8]) + ",")
    out.append("};")
    out.append("")

sys.stdout.write("\n".join(out) + "\n")
